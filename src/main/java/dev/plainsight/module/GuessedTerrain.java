package dev.plainsight.module;

import dev.infiniterra.api.TerrainGuess;
import dev.plainsight.guess.SeedStore;
import imgui.ImDrawList;
import imgui.ImGui;

/**
 * Shows terrain generated from the world seed wherever no real chunks have been seen (editor only, with
 * Voxy), with a faint blue tint that fades in and out so guesses are never mistaken for the real
 * world.
 */
public final class GuessedTerrain implements Module {
	private boolean enabled = true;
	private final int[] radius = {TerrainGuess.radius()};
	/** Strongest blue tint of guessed chunks (it fades down to a quarter of this and back). */
	public static volatile float tintOpacity = 0.2f;
	/** Seconds for one fade cycle. */
	public static volatile float pulseSeconds = 0.5f;
	public static final float MIN_PULSE = 0.2f, MAX_PULSE = 5f;
	private final float[] opacity = {tintOpacity}, pulse = {pulseSeconds};

	@Override
	public String id() {
		return "guessed_terrain";
	}

	@Override
	public String name() {
		return "Guessed Terrain";
	}

	@Override
	public String description() {
		return "Terrain generated from the world seed where you have not been, with a fading blue tint. Right-click for settings.";
	}

	@Override
	public boolean enabled() {
		return enabled;
	}

	@Override
	public void setEnabled(boolean e) {
		enabled = e;
	}

	/** Whether guessed terrain should be shown right now (a seed is known and its world is ready). */
	public boolean active() {
		TerrainGuess.Status w = TerrainGuess.current();
		return enabled && w != null && w.state() == TerrainGuess.State.READY;
	}

	@Override
	public void options() {
		TerrainGuess.Status w = TerrainGuess.current();
		var seed = SeedStore.seed();
		ImGui.text(seed.isPresent() ? "Seed " + dev.plainsight.guess.SeedHider.show(seed.getAsLong()) + " (" + SeedStore.source() + ")" : "No seed known");
		if (seed.isPresent()) ImGui.textDisabled(dev.plainsight.guess.GuessCommands.checkText());
		if (w == null) {
			ImGui.textDisabled(TerrainGuess.supported() ? "SeedcrackerX finds it, or /plainsight seed <seed>" : "Needs Voxy to show guessed terrain");
			return;
		}
		switch (w.state()) {
			case STARTING -> ImGui.textDisabled("Starting the world generator...");
			case FAILED -> {
				ImGui.textColored(0xFF6060FF, "Generator failed: " + w.error());
				if (ImGui.button("Retry")) TerrainGuess.retry();
			}
			case READY -> {
				ImGui.textDisabled(w.guessedCount() + " chunks generated, " + w.realCount() + " real, " + w.pending() + " pending");
				if (w.importTotal() > 0 && w.imported() < w.importTotal())
					ImGui.textDisabled("Copying your Voxy LOD: " + w.imported() + " / " + w.importTotal() + " columns"
							+ (TerrainGuess.showing() ? " (slowly while shown)" : ""));
				if (ImGui.button("Reload view")) w.reloadView();
				if (ImGui.isItemHovered()) ImGui.setTooltip("Has Voxy rebuild the guessed terrain from what is stored (fixes leftover holes).");
			}
		}
		opacity[0] = tintOpacity;
		ImGui.setNextItemWidth(160);
		if (ImGui.sliderFloat("Tint", opacity, 0.02f, 0.4f, "%.2f")) tintOpacity = opacity[0];
		pulse[0] = pulseSeconds;
		ImGui.setNextItemWidth(160);
		if (ImGui.sliderFloat("Fade cycle", pulse, MIN_PULSE, MAX_PULSE, "%.1f s")) pulseSeconds = pulse[0];
		radius[0] = TerrainGuess.radius();
		ImGui.setNextItemWidth(160);
		if (ImGui.sliderInt("Radius (chunks)", radius, 4, 128)) TerrainGuess.setRadius(radius[0]);
		ImGui.textDisabled("Natural terrain only: no builds, and\nchunks generated by older versions differ.");
	}

	@Override
	public void saveSettings(com.google.gson.JsonObject o) {
		o.addProperty("radiusChunks", TerrainGuess.radius());
		o.addProperty("tintOpacity", tintOpacity);
		o.addProperty("fadeCycleSeconds", pulseSeconds);
	}

	@Override
	public void loadSettings(com.google.gson.JsonObject o) {
		TerrainGuess.setRadius(Math.max(4, Math.min(128, ModuleConfig.getInt(o, "radiusChunks", TerrainGuess.radius()))));
		float tint = ModuleConfig.getFloat(o, "tintOpacity", tintOpacity);
		float pulse = ModuleConfig.getFloat(o, "fadeCycleSeconds", pulseSeconds);
		// the old defaults (0.12, 6 s) were saved as settings: they take the new ones
		if (tint == 0.12f) tint = tintOpacity;
		if (pulse == 6f) pulse = pulseSeconds;
		tintOpacity = Math.max(0.02f, Math.min(0.4f, tint));
		pulseSeconds = Math.max(MIN_PULSE, Math.min(MAX_PULSE, pulse));
	}

	@Override
	public void drawIcon(ImDrawList dl, float x, float y, float size, int color) {
		// a hill with a question mark: terrain that is guessed
		dl.addTriangleFilled(x + size * 0.12f, y + size * 0.84f, x + size * 0.42f, y + size * 0.42f, x + size * 0.72f, y + size * 0.84f, color);
		dl.addCircle(x + size * 0.7f, y + size * 0.32f, size * 0.13f, color, 12, 2f);
		dl.addCircleFilled(x + size * 0.7f, y + size * 0.62f, size * 0.05f, color, 8);
	}
}
